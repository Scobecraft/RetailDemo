package main

import (
	"os"
	"testing"
)

// G-Code vom Server-Slicer (PrusaSlicer) liefert Druckzeit und Filament für die Anzeige
func TestPrusaSlicerMeta(t *testing.T) {
	g := "; generated by PrusaSlicer 2.7.2\nG1 X0\n; filament used [mm] = 1295.83\n; filament used [g] = 3.9\n; estimated printing time (normal mode) = 13m 28s\n; layer_height = 0.2\n; nozzle_diameter = 0.4\n; temperature = 215\n; bed_temperature = 60\n; filament_type = PLA\n; fill_density = 15%\n"
	f, _ := os.CreateTemp("", "*.gcode")
	f.WriteString(g)
	f.Close()
	defer os.Remove(f.Name())
	m := readFileMeta(f.Name(), "Test.gcode")
	if m.TimeSec != 808 || m.FilamentG < 3.8 || m.LayerHeight != 0.2 {
		t.Fatalf("Angaben nicht erkannt: %+v", m)
	}
}
